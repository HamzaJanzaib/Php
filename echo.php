<?php

// echo is the language construct used to output text to the browser. It can be used with or without parentheses. In this case, we are using it without parentheses to output the string "Hello, World!" and "Welcome to my website." The <br> tag is used to create a line break between the two outputs.


echo "Learning PHP Echo!";
echo "<br>";
echo "This is a simple example of using echo in PHP.";

echo "<br>";
echo "sum for 10 + 20 is: ";
echo (10 + 20); // This will output the sum of 10 and 20, which is 30.
echo "<br>";

echo "sum for 10 + 20 is: " . (10 + 20);
echo "<br>";
echo "sum for 10 + 20 is: " . (10 + 20) . " and this is the end of the line.";
echo "<br>";
